@Injectable({ providedIn: 'root' })
export class I18n {
  readonly lang = signal<Lang>(I18n.initial());
  readonly dir = computed(() => (this.lang() === 'ur' ? 'rtl' : 'ltr'));
  readonly isUr = computed(() => this.lang() === 'ur');

  private static initial(): Lang {
    try { return (localStorage.getItem('lang') as Lang) === 'ur' ? 'ur' : 'en'; } catch { return 'en'; }
  }

  constructor() { this.apply(); }

  set(lang: Lang) {
    this.lang.set(lang);
    try { localStorage.setItem('lang', lang); } catch { /* storage unavailable */ }
    this.apply();
  }

  private apply() {
    const l = this.lang();
    document.documentElement.lang = l;
    document.documentElement.dir = l === 'ur' ? 'rtl' : 'ltr';
  }

  t(key: string, ...args: unknown[]): string {
    return I18n.translate(this.lang(), key, ...args);
  }

  static translate(lang: Lang, key: string, ...args: unknown[]): string {
    const entry = T[key];
    let s = entry ? entry[lang === 'ur' ? 1 : 0] : key;
    args.forEach((a, i) => (s = s.replace(`{${i}}`, String(a))));
    return s;
  }

  /** Picks the Urdu field when Urdu is active and the field has a value. */
  pick(en: string | null | undefined, ur: string | null | undefined): string {
    return this.lang() === 'ur' && ur ? ur : en ?? '';
  }

  static has(key: string) { return key in T; }
}

@Pipe({ name: 't', standalone: true, pure: false })
export class TPipe implements PipeTransform {
  constructor(private i18n: I18n) {}
  transform(key: string, ...args: unknown[]): string { return this.i18n.t(key, ...args); }
}
